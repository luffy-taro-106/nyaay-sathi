def classify_case(user_text: str) -> CaseCategory:
    """Order matters: consumer before employment so 'payment receipt' / invoice follow-ups are not mis-tagged as wages."""
    text = user_text.lower()
    if any(term in text for term in PROPERTY_TERMS):
        return "property_tenancy"
    if any(term in text for term in WOMEN_PROTECTION_TERMS):
        return "womens_protection"
    if any(term in text for term in CONSUMER_TERMS):
        return "consumer_fraud"
    if any(term in text for term in EMPLOYMENT_TERMS):
        return "employment_wages"
    if any(term in text for term in POLICE_TERMS):
        return "police_fir"
    return "general"
